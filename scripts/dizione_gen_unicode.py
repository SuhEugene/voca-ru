"""Generate crates/dizione/src/unicode_tables.rs: the character classes of the
Python that the reference dizione runs on (str.isalnum, isalpha, isdigit,
isdecimal, isspace), so the Rust port classifies every character identically."""
import sys, unicodedata
def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        c = chr(cp)
        ok = not (0xD800 <= cp <= 0xDFFF) and pred(c)
        if ok and start is None: start = cp
        if not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out
tables = {"ALNUM": str.isalnum, "ALPHA": str.isalpha, "DIGIT": str.isdigit, "DECIMAL": str.isdecimal, "SPACE": str.isspace}
lines = [f"// Generated by scripts/dizione_gen_unicode.py from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n"]
for name, pred in tables.items():
    r = ranges(pred)
    lines.append(f"pub static {name}: [(u32, u32); {len(r)}] = [")
    for i in range(0, len(r), 8):
        lines.append("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in r[i:i+8]))
    lines.append("];\n")
zeros = [cp for cp in range(0x110000) if not (0xD800 <= cp <= 0xDFFF) and chr(cp).isdigit() and unicodedata.digit(chr(cp), -1) == 0]
# digit value of every isdigit() char: (codepoint, value) runs
vals = [(cp, unicodedata.digit(chr(cp))) for cp in range(0x110000) if not (0xD800 <= cp <= 0xDFFF) and chr(cp).isdigit()]
runs = []
for cp, v in vals:
    if runs and runs[-1][0] + runs[-1][2] == cp and runs[-1][1] + runs[-1][2] == v:
        runs[-1][2] += 1
    else:
        runs.append([cp, v, 1])
lines.append(f"/// (first code point, digit value of the first, length): values rise by one along a run.\npub static DIGIT_VALUES: [(u32, u8, u8); {len(runs)}] = [")
for i in range(0, len(runs), 6):
    lines.append("    " + " ".join(f"(0x{a:X}, {v}, {n})," for a, v, n in runs[i:i+6]))
lines.append("];")
open("crates/dizione/src/unicode_tables.rs", "w").write("\n".join(lines) + "\n")
print({k: len(ranges(p)) for k, p in tables.items()}, len(runs))
